// Builds dist/: compiled ESM and types with tsc, then tokens.css and
// tokens.json generated from the compiled token module, plus the hand-written
// stylesheets and the bundled fonts with their license files.
import { execFileSync } from "node:child_process";
import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");

rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });

execFileSync(
  join(root, "node_modules/.bin/tsc"),
  ["-p", join(root, "tsconfig.build.json")],
  { stdio: "inherit" },
);

// tsc keeps extensionless specifiers. Rewriting them makes dist/ valid native
// ESM, so a consumer's Node based test runner can load it as well as a bundler.
function fixSpecifiers(dir) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      fixSpecifiers(path);
    } else if (/\.(js|d\.ts)$/.test(entry.name)) {
      const fixed = readFileSync(path, "utf8").replace(
        /(from\s+|import\()"(\.{1,2}\/[^"]+)"/g,
        (_, prefix, spec) => {
          const isDir = existsSync(join(dirname(path), spec, "index.js"));
          return `${prefix}"${spec}${isDir ? "/index.js" : ".js"}"`;
        },
      );
      writeFileSync(path, fixed);
    }
  }
}
fixSpecifiers(dist);

const tokensUrl = pathToFileURL(join(dist, "tokens/index.js")).href;
const {
  tokens,
  themes,
  cssVarName,
  DEFAULT_THEME,
  REDUCED_MOTION_DURATION,
} = await import(tokensUrl);

const declarations = (group, values) =>
  Object.entries(values).map(
    ([key, value]) => `  ${cssVarName(group, key)}: ${value};`,
  );

function themeBlock(selector, theme, mode) {
  const lines = [
    `  color-scheme: ${mode};`,
    ...declarations("color", theme.color[mode]),
    ...declarations("shadow", theme.elevation[mode]),
  ];
  return `${selector} {\n${lines.join("\n")}\n}`;
}

function renderTokensCss() {
  const scales = [
    ...declarations("space", tokens.space),
    ...declarations("radius", tokens.radius),
    ...declarations("font", tokens.font),
    ...declarations("font-size", tokens.fontSize),
    ...declarations("font-weight", tokens.fontWeight),
    ...declarations("line-height", tokens.lineHeight),
    ...declarations("motion", tokens.motion),
    ...declarations("easing", tokens.easing),
    ...declarations("z", tokens.zIndex),
  ];
  const reduced = declarations(
    "motion",
    Object.fromEntries(
      Object.keys(tokens.motion).map((key) => [key, REDUCED_MOTION_DURATION]),
    ),
  );

  const blocks = [
    "/* Generated by scripts/build.mjs from src/tokens/index.ts. Do not edit. */",
    "/* data-theme selects the mode: absent follows the OS, or light or dark. */",
    "/* data-palette selects the theme: absent is the default, or nordic. */",
    `:root {\n${scales.join("\n")}\n}`,
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${reduced
      .map((line) => `  ${line}`)
      .join("\n")}\n  }\n}`,
  ];

  for (const [name, theme] of Object.entries(themes)) {
    const palette = name === DEFAULT_THEME ? "" : `[data-palette="${name}"]`;
    blocks.push(themeBlock(`:root${palette}`, theme, "light"));
    const dark = themeBlock(
      `:root${palette}:not([data-theme="light"])`,
      theme,
      "dark",
    );
    blocks.push(
      `@media (prefers-color-scheme: dark) {\n${dark
        .split("\n")
        .map((line) => `  ${line}`)
        .join("\n")}\n}`,
    );
    blocks.push(themeBlock(`:root${palette}[data-theme="dark"]`, theme, "dark"));
  }
  return `${blocks.join("\n\n")}\n`;
}

const tokensCss = renderTokensCss();
writeFileSync(join(dist, "tokens.css"), tokensCss);
writeFileSync(join(dist, "tokens.json"), `${JSON.stringify(tokens, null, 2)}\n`);

const fontsCss = readFileSync(join(root, "src/styles/fonts.css"), "utf8");
const componentsCss = readFileSync(
  join(root, "src/styles/components.css"),
  "utf8",
);
writeFileSync(join(dist, "fonts.css"), fontsCss);
writeFileSync(join(dist, "components.css"), componentsCss);
writeFileSync(
  join(dist, "styles.css"),
  `${fontsCss}\n${tokensCss}\n${componentsCss}`,
);

cpSync(join(root, "src/fonts"), join(dist, "fonts"), { recursive: true });

console.log("Built dist/");
